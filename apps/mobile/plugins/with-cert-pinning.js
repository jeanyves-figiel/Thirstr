// #168 certificate pinning (security.md › Transport, docs/runbooks/cert-pinning.md).
// Pins the API hosts to CA public keys (SPKI SHA-256), not to our leaf certificate: Fly renews the
// Let's Encrypt leaf every ~60 days and that must never break the app.
// iOS: Info.plist NSPinnedDomains (system TLS, iOS 14+). Android: network_security_config pin-set
// (with an expiration, after which Android stops enforcing it instead of breaking the app).
// Build with THIRSTR_CERT_PINNING=off to leave pinning out (emergency builds only).
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, withInfoPlist } = require('expo/config-plugins');

// Every value: base64(SHA-256(SubjectPublicKeyInfo DER)). Sources and how to recompute: runbook.
const PINS = [
  { name: 'ISRG Root X1', spki: 'C5+lpZ7tcVwmwQIMcRtPbsQtWLABXhQzejna0wHFr8M=' },
  { name: 'ISRG Root X2', spki: 'diGVwiVYbubAI3RW4hB9xU8e/CH2GnkuvVFZE8zmgzI=' },
  { name: 'ISRG Root YR', spki: 'fk6IOKit1ild5647BH06ujSIq5XbCgqlbYl6ANhhi88=' },
  { name: 'ISRG Root YE', spki: 'sCkq5UWXjg+7mKu9lMhhYF5bGLsy7VI/UNW3tccdR7w=' },
  // Backup CA (not used today): lets us move certificates off Let's Encrypt without an app update.
  { name: 'GTS Root R1', spki: 'hxqRlPTu1bMS/0DITB1SSu0vd4u/8l8TjPgfaAp63Gc=' },
  { name: 'GTS Root R4', spki: 'mEflZT5enoR1FuXLgYYGqnVEoZvmf9c2bVBpiOjYQ0c=' },
];
const ANDROID_EXPIRATION = '2028-06-30';
const DEFAULT_HOSTS = ['api.thirstr.fun', 'staging.thirstr.fun'];

function hosts() {
  const set = new Set(DEFAULT_HOSTS);
  const api = process.env.EXPO_PUBLIC_API_URL;
  if (api) {
    const u = new URL(api);
    if (u.protocol === 'https:' && (u.hostname === 'thirstr.fun' || u.hostname.endsWith('.thirstr.fun'))) set.add(u.hostname);
  }
  return [...set];
}

function androidXml(hs) {
  const pins = PINS.map((p) => `      <pin digest="SHA-256">${p.spki}</pin> <!-- ${p.name} -->`).join('\n');
  const domains = hs.map((h) => `    <domain includeSubdomains="false">${h}</domain>`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-cert-pinning.js (#168). Do not edit by hand. -->
<network-security-config>
  <domain-config cleartextTrafficPermitted="false">
${domains}
    <pin-set expiration="${ANDROID_EXPIRATION}">
${pins}
    </pin-set>
  </domain-config>
  <!-- Dev builds talk to Metro / DEV stack over plain HTTP on the local machine only. -->
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">localhost</domain>
    <domain includeSubdomains="false">10.0.2.2</domain>
    <domain includeSubdomains="false">127.0.0.1</domain>
  </domain-config>
</network-security-config>
`;
}

module.exports = function withCertPinning(config) {
  if (process.env.THIRSTR_CERT_PINNING === 'off') return config;
  const hs = hosts();

  config = withInfoPlist(config, (c) => {
    const ats = { ...(c.modResults.NSAppTransportSecurity || {}) };
    const pinned = { ...(ats.NSPinnedDomains || {}) };
    for (const h of hs) {
      pinned[h] = {
        NSIncludesSubdomains: false,
        NSPinnedCAIdentities: PINS.map((p) => ({ 'SPKI-SHA256-BASE64': p.spki })),
      };
    }
    ats.NSPinnedDomains = pinned;
    c.modResults.NSAppTransportSecurity = ats;
    return c;
  });

  config = withDangerousMod(config, [
    'android',
    async (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), androidXml(hs));
      return c;
    },
  ]);

  config = withAndroidManifest(config, (c) => {
    const app = c.modResults.manifest.application?.[0];
    if (app) app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return c;
  });

  return config;
};

module.exports.PINS = PINS;
module.exports.androidXml = androidXml;
module.exports.hosts = hosts;
