export type AppStrings = typeof en;
export type Partialize<T> = { [K in keyof T]?: T[K] extends (...a: never[]) => unknown ? T[K] : T[K] extends object ? Partialize<T[K]> : T[K] };

function merge<T>(base: T, over: Partialize<T>): T {
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const [k, v] of Object.entries(over as Record<string, unknown>)) {
    const b = (base as Record<string, unknown>)[k];
    out[k] = v && typeof v === 'object' && !Array.isArray(v) && b && typeof b === 'object' ? merge(b, v as Partialize<typeof b>) : v;
  }
  return out as T;
}

function pick(): AppStrings {
  const lang = getLocales()[0]?.languageCode ?? 'en';
  return lang === 'fr' ? merge(en, fr) : lang === 'de' ? merge(en, de) : en;
}

export const tx = pick();
export { en as txEn };

const OPT = OPTION_LABELS[getLocales()[0]?.languageCode ?? 'en'] ?? OPTION_LABELS.en;

/** Option label in the app language ("vers_top" → "Vers top" / "Plutôt actif"); languages show their own name. */
export function opt(value: string, field?: string): string {
  if (field === 'languages') return LANGUAGE_NAMES[value] ?? value.toUpperCase();
  if (OPT[value]) return OPT[value];
  const s = value.replace(/_/g, ' ');
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/** Field label without a unit suffix, for read-only display ("Height (cm)" → "Height"). */
export const bareLabel = (label: string) => label.replace(/\s*\([^)]*\)\s*$/, '');

export function distanceLabel(d: { kind: string; m?: number; bucket?: string; city?: string | null; floor?: boolean; approx?: boolean } | null): string {
  if (!d) return '';
  const mi = inMiles(d);
  if (mi) return mi;
  if (d.kind === 'exact') return tx.distance.m(d.m ?? 0);
  if (d.kind === 'city') return tx.distance.city(d.city ?? null);
  // #197 R-04.6: rounded number ("~150 m", "< 100 m"); buckets when the server sends none.
  if (typeof d.m === 'number') return `${d.floor ? '< ' : d.approx ? '~' : ''}${tx.distance.m(d.m)}`;
  return (tx.distance as unknown as Record<string, string>)[d.bucket ?? ''] ?? '';
}
